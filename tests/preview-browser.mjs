import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { chromium } from "playwright";

const BASE = "https://course-preview-preview.up.railway.app";
const PROD = "https://course-planner-publish-production.up.railway.app";
const BACK = "https://analytics-qa-preview.up.railway.app";
const browser = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
let context;
function check(condition, msg) { assert.ok(condition, msg); console.log("PASS:",msg); }
async function test() {
  context = await browser.newContext({ viewport:{width:1365,height:840}, locale:"zh-CN" });
  const request = context.request;
  const health = await request.get(BASE+"/health");
  check(health.status()===200,"Preview HTTP health 200");
  const previewResponse = await request.get(BASE+"/");
  check(previewResponse.status()===200 && (previewResponse.headers()["content-type"]||"").includes("text/html"),"Preview HTML response not code/text");
  const sourceResponse = await request.get(PROD+"/");
  check(sourceResponse.status()===200,"Unmodified production baseline online");
  const previewHtml = await previewResponse.text();
  const productionHtml = await sourceResponse.text();
  const sourceHtml = productionHtml.replace("<link rel=\"stylesheet\" href=\"https://course-analytics-production-974e741c.up.railway.app/site-consent.css\"><script defer src=\"https://course-analytics-production-974e741c.up.railway.app/site-consent.js\"></script>", "");
  const marker='<link rel="stylesheet" href="https://analytics-qa-preview.up.railway.app/site-consent.css"><script defer src="https://analytics-qa-preview.up.railway.app/site-consent.js"></script>';
  check(previewHtml.includes(marker),"Preview loads external privacy module");
  const extracted = previewHtml.replace(marker,"");
  check(extracted===sourceHtml,"Preview page equals the current production HTML byte-for-byte after removing the preview-only addition");
  const infoRes = await request.get(BASE+"/preview-info");
  const info = await infoRes.json();
  check(info.sourceSha256===createHash("sha256").update(sourceHtml).digest("hex"),"Preview source fingerprint matches current production HTML");
  const page = await context.newPage();
  let eventRequests=[];
  const errors=[];
  page.on("request",req=>{if(req.url().includes("/api/track"))eventRequests.push(req.url())});
  page.on("pageerror",err=>errors.push(String(err.message||err)));
  const navigated = await page.goto(BASE+"/",{waitUntil:"domcontentloaded",timeout:45000});
  check(navigated?.status()===200,"Actual Chromium navigation returns 200");
  await page.waitForTimeout(1500);
  const body = await page.locator("body").innerText();
  check(body.length>100 && body.length<120000 && !body.startsWith("const N=Number("),"Normal rendered app interface, not raw code");
  check((await page.locator("[data-act]").count())>=5,"Original selection and assistant controls are in rendered DOM");
  check((await page.locator("#cp-preview-badge").count())===1,"Preview environment visually distinguished");
  check(await page.locator("#cp-preview-consent").isVisible(),"Consent dialog shown before tracking");
  check(eventRequests.length===0,"No visitor data submitted before consent");
  await page.screenshot({path:"preview-before-consent.png",fullPage:false});
  await page.locator("#cp-preview-decline").click();
  check((await page.locator("#cp-preview-consent").count())===0,"Declining hides the consent dialog");
  await page.waitForTimeout(700);
  check(eventRequests.length===0,"Declining never loads tracking");
  await page.reload({waitUntil:"domcontentloaded"});
  await page.waitForTimeout(650);
  check((await page.locator("#cp-preview-consent").count())===0,"Decline persists across reload");
  check(eventRequests.length===0,"No tracking after decline and reload");
  await page.locator("#cp-preview-settings").click();
  check(await page.locator("#cp-preview-consent").isVisible(),"Privacy choice can be reopened");
  const waitTracking=page.waitForResponse(res=>res.url().startsWith(BACK+"/api/track") && res.request().method()==="POST", {timeout:20000});
  await page.locator("#cp-preview-accept").click();
  const tracked=await waitTracking;
  check(tracked.status()===204,"Consent leads to real network event successfully written (204)");
  await page.waitForFunction(()=>typeof window.CourseAnalytics?.track==="function",{timeout:15000});
  check(await page.evaluate(()=>window.CoursePreviewAnalytics.status().consent==="yes"),"Consent recorded on preview page");
  const custom=page.waitForResponse(res=>res.url().startsWith(BACK+"/api/track") && res.request().postData()?.includes("manual_select"),{timeout:12000});
  await page.evaluate(()=>window.CourseAnalytics.track("manual_select"));
  check((await custom).status()===204,"Manual selection event accepted in staging database");
  await page.screenshot({path:"preview-after-consent.png",fullPage:false});
  check(errors.length===0,"No uncaught browser JavaScript exception: "+errors.slice(0,3).join(" | "));
  await page.reload({waitUntil:"domcontentloaded"});
  await page.waitForTimeout(1100);
  check((await page.locator("#cp-preview-consent").count())===0,"Accept persists across reload");
  check((await page.locator("#cp-preview-tracker-script").count())===1,"Tracker auto-loads only after saved consent");
  await page.locator("#cp-preview-settings").click();
  await page.locator("#cp-preview-decline").click();
  await page.waitForLoadState("domcontentloaded");
  await page.waitForTimeout(650);
  check(await page.evaluate(()=>localStorage.getItem("course_planner_preview_analytics_consent_v2")==="no"),"Revocation stored");
  check((await page.locator("#cp-preview-tracker-script").count())===0,"Revoking consent stops tracking after reload");
  console.log("SUCCESS: isolated browser preview tests passed");
}
try { await test(); } finally { await context?.close().catch(()=>{}); await browser.close(); }
