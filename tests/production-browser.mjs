import assert from "node:assert/strict";
import { chromium } from "playwright";
const PROD = "https://course-planner-publish-production.up.railway.app";
const PREVIEW = "https://course-preview-preview.up.railway.app";
const BACK = "https://course-analytics-production-974e741c.up.railway.app";
const prodAddon='<link rel="stylesheet" href="'+BACK+'/site-consent.css"><script defer src="'+BACK+'/site-consent.js"></script>';
const previewAddon='<link rel="stylesheet" href="https://analytics-qa-preview.up.railway.app/site-consent.css"><script defer src="https://analytics-qa-preview.up.railway.app/site-consent.js"></script>';
const ok=(x,desc)=>{assert.ok(x,desc);console.log("PASS:",desc)};
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
let ctx;
try {
  ctx=await browser.newContext({viewport:{width:1365,height:850},locale:"zh-CN"});
  const prodReq=await ctx.request.get(PROD+"/");
  ok(prodReq.status()===200 && (prodReq.headers()["content-type"]||"").includes("text/html"),"Production returns HTML 200, not source code");
  const prodHtml=await prodReq.text();
  ok(prodHtml.includes(prodAddon) && prodHtml.split(prodAddon).length===2,"Production includes exactly one external consent module");
  const pureProd=prodHtml.replace(prodAddon,"");
  const prevReq=await ctx.request.get(PREVIEW+"/");
  ok(prevReq.status()===200,"Isolated preview still available");
  const prevHtml=await prevReq.text();
  ok(prevHtml.replace(previewAddon,"")===pureProd,"Production original HTML is byte-identical to isolated preview baseline after removing analytics tags");
  for(const marker of ["BUILT_CURRENT_SPRING","hbAMlCk","manual-entry","assist-run","survey-confirm"]){
    ok(pureProd.includes(marker),"Original course feature preserved: "+marker);
  }
  const page=await ctx.newPage();
  const pageErrors=[],trackedRequests=[];
  page.on("pageerror",x=>pageErrors.push(x.message));
  page.on("request",x=>{if(x.url().startsWith(BACK+"/api/track"))trackedRequests.push(x.url());});
  const response=await page.goto(PROD+"/",{waitUntil:"domcontentloaded",timeout:45000});
  ok(response?.status()===200,"Real Chromium loads production page");
  await page.waitForTimeout(1300);
  const body=await page.locator("body").innerText();
  ok(body.length>100 && body.length<120000 && !body.startsWith("const N=Number("),"Production renders normal UI instead of raw code");
  ok((await page.locator("[data-act]").count())>=5,"Course planner controls render in browser");
  ok((await page.locator("#cp-preview-consent").count())===1,"Consent dialog appears for new user");
  ok((await page.locator("#cp-preview-badge").count())===0,"Production does not display QA banner");
  ok(trackedRequests.length===0,"No visitor tracking before consent");
  await page.screenshot({path:"production-consent-before.png"});
  await page.locator("#cp-preview-decline").click();
  await page.waitForTimeout(400);
  ok(trackedRequests.length===0,"Declining blocks analytics");
  await page.reload({waitUntil:"domcontentloaded"});
  await page.waitForTimeout(500);
  ok((await page.locator("#cp-preview-consent").count())===0 && trackedRequests.length===0,"Decline persists across reload");
  await page.locator("#cp-preview-settings").click();
  ok((await page.locator("#cp-preview-consent").count())===1,"Privacy settings can be reopened");
  const reporting=page.waitForResponse(r=>r.url().startsWith(BACK+"/api/track")&&r.request().method()==="POST",{timeout:15000});
  await page.locator("#cp-preview-accept").click();
  const accepted=await reporting;
  ok(accepted.status()===204,"Consent leads to successfully accepted real production event (204)");
  await page.waitForFunction(()=>typeof window.CourseAnalytics?.track==="function");
  ok((await page.locator("#cp-preview-tracker-script").count())===1,"Tracker loaded after consent");
  await page.screenshot({path:"production-consent-after.png"});
  ok(pageErrors.length===0,"No uncaught JavaScript errors: "+pageErrors.join(" | "));
  await page.locator("#cp-preview-settings").click();
  await page.locator("#cp-preview-decline").click();
  await page.waitForLoadState("domcontentloaded");
  await page.waitForTimeout(500);
  ok(await page.evaluate(()=>localStorage.getItem("course_planner_analytics_consent_v2")==="no"),"Privacy revocation stored");
  ok((await page.locator("#cp-preview-tracker-script").count())===0,"Revoking consent removes tracker on reload");
  console.log("SUCCESS: full production Chromium privacy and UI regression passed");
} finally {await ctx?.close().catch(()=>{});await browser.close();}
